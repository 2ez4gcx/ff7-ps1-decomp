/* AKAO sound driver ---------------------------------------------------- */

/* A request in the driver's queue. The song commands (0x10, 0x14, 0x15,
 * table at 0x80049548) read the sequence to load and the song from it. */
typedef struct {
    s32 unk0;
    u8 *sequence; /* 0x04 */
    s32 size;     /* 0x08: bytes */
    u16 song;     /* 0x0C */
} AkaoCommand;

/* A song's own state (its channels are apart): 0x60 bytes. */
typedef struct {
    s32 unk0;
    s32 active;   /* 0x04: one bit per channel playing */
    s32 unk8;
    s32 unkC;
    s32 unk10;
    s32 unk14;
    s32 unk18;
    s32 unk1C;
    s32 unk20;
    s32 unk24;
    s32 unk28;
    s32 unk2C;
    s32 unk30;
    s32 unk34;
    s32 unk38;
    s32 unk3C;
    s32 unk40;
    s32 unk44;
    u16 unk48;
    u16 id;       /* 0x4A: the song, 0 for none */
    u16 unk4C;
    u16 unk4E;
    u16 unk50;
    u16 unk52;
    u16 unk54;
    u16 unk56;
    u16 unk58;
    u16 unk5A;
    u16 unk5C;
    u16 unk5E;
} AkaoSong;

/* A channel of a song: 0x108 bytes. */
typedef struct {
    u8 *addr;          /* 0x00: where it reads its sequence */
    u8 pad4[0x10];
    u8 *start;         /* 0x14 */
    u8 pad18[0x14];
    s32 unk2C;         /* 0x2C */
    u8 pad30[0x4];
    s32 unk34;         /* 0x34 */
    s32 unk38;         /* 0x38 */
    u8 pad3C[0x8];
    s32 unk44;         /* 0x44 */
    u8 pad48[0x8];
    s32 unk50;         /* 0x50 */
    u16 unk54;         /* 0x54 */
    u16 unk56;         /* 0x56 */
    u8 pad58[0x4];
    u16 unk5C;         /* 0x5C */
    u16 unk5E;         /* 0x5E */
    u16 unk60;         /* 0x60 */
    u16 unk62;         /* 0x62 */
    u16 unk64;         /* 0x64 */
    u8 pad66[0x6];
    u16 unk6C;         /* 0x6C */
    u16 unk6E;         /* 0x6E */
    u8 pad70[0xE];
    u16 unk7E;         /* 0x7E */
    u16 unk80;         /* 0x80 */
    u8 pad82[0xE];
    u16 unk90;         /* 0x90 */
    u16 unk92;         /* 0x92 */
    u8 pad94[0xA];
    u16 unk9E;         /* 0x9E */
    u16 unkA0;         /* 0xA0 */
    u8 padA2[0x2];
    u16 unkA4;         /* 0xA4 */
    u16 unkA6;         /* 0xA6 */
    u8 padA8[0x10];
    u16 unkB8;         /* 0xB8 */
    u8 padBA[0x8];
    u16 unkC2;         /* 0xC2 */
    u16 unkC4;         /* 0xC4 */
    u16 unkC6;         /* 0xC6 */
    u8 padC8[0x4];
    u16 unkCC;         /* 0xCC */
    u16 unkCE;         /* 0xCE */
    u8 padD0[0x2];
    u16 unkD2;         /* 0xD2 */
    u8 padD4[0x6];
    u16 unkDA;         /* 0xDA */
    u8 padDC[0x4];
    s32 unkE0;         /* 0xE0 */
    u8 padE4[0x24];
} AkaoChannel;


